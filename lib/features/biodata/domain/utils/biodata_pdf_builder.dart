import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:walima_llc/features/biodata/domain/model/biodata_document.dart';

class BiodataPdfBuilder {
  const BiodataPdfBuilder._();

  static Future<Uint8List> build({
    required BiodataDocument biodata,
    required BiodataTemplate template,
  }) async {
    final colors = _templateColors(template);
    final document = pw.Document();
    final profileImage = await _loadProfileImage(biodata.profileImageUrl);

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (context) => [
          _header(
            biodata: biodata,
            profileImage: profileImage,
            colors: colors,
          ),
          if (biodata.bio.isNotEmpty) ...[
            pw.SizedBox(height: 18),
            _section(
              title: 'About',
              children: [
                pw.Text(
                  biodata.bio,
                  style: pw.TextStyle(
                    fontSize: 10.5,
                    height: 1.35,
                    color: colors.text,
                  ),
                ),
              ],
              colors: colors,
            ),
          ],
          ...biodata.sections.map(
            (section) => pw.Padding(
              padding: const pw.EdgeInsets.only(top: 14),
              child: _section(
                title: section.title,
                children: [_itemsTable(section.items, colors)],
                colors: colors,
              ),
            ),
          ),
          pw.SizedBox(height: 22),
          pw.Align(
            alignment: pw.Alignment.center,
            child: pw.Text(
              'Generated by Walima',
              style: pw.TextStyle(fontSize: 9, color: colors.muted),
            ),
          ),
        ],
      ),
    );

    return document.save();
  }

  static String fileNameFor(BiodataDocument biodata) {
    final name = biodata.fullName.trim().isEmpty
        ? 'walima_biodata'
        : biodata.fullName.trim();
    final safe = name
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-z0-9]+'), '_')
        .replaceAll(RegExp(r'_+'), '_')
        .replaceAll(RegExp(r'^_|_$'), '');
    return '${safe.isEmpty ? 'walima_biodata' : safe}_biodata.pdf';
  }

  static pw.Widget _header({
    required BiodataDocument biodata,
    required pw.ImageProvider? profileImage,
    required _PdfTemplateColors colors,
  }) {
    return pw.Container(
      padding: const pw.EdgeInsets.all(18),
      decoration: pw.BoxDecoration(
        color: colors.headerBackground,
        borderRadius: pw.BorderRadius.circular(14),
        border: pw.Border.all(color: colors.border),
      ),
      child: pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.center,
        children: [
          pw.Container(
            width: 86,
            height: 86,
            decoration: pw.BoxDecoration(
              shape: pw.BoxShape.circle,
              color: PdfColors.white,
              border: pw.Border.all(color: colors.accent, width: 2),
            ),
            child: profileImage == null
                ? pw.Center(
                    child: pw.Text(
                      _initials(biodata.fullName),
                      style: pw.TextStyle(
                        fontSize: 24,
                        fontWeight: pw.FontWeight.bold,
                        color: colors.accent,
                      ),
                    ),
                  )
                : pw.ClipOval(
                    child: pw.Image(profileImage, fit: pw.BoxFit.cover),
                  ),
          ),
          pw.SizedBox(width: 18),
          pw.Expanded(
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text(
                  biodata.fullName.isEmpty
                      ? 'Walima Biodata'
                      : biodata.fullName,
                  style: pw.TextStyle(
                    fontSize: 24,
                    fontWeight: pw.FontWeight.bold,
                    color: colors.title,
                  ),
                ),
                pw.SizedBox(height: 8),
                pw.Text(
                  'Marriage Biodata',
                  style: pw.TextStyle(
                    fontSize: 12,
                    letterSpacing: 1.1,
                    color: colors.accent,
                  ),
                ),
              ],
            ),
          ),
        ],
      ),
    );
  }

  static pw.Widget _section({
    required String title,
    required List<pw.Widget> children,
    required _PdfTemplateColors colors,
  }) {
    return pw.Container(
      padding: const pw.EdgeInsets.all(14),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: colors.border),
        borderRadius: pw.BorderRadius.circular(10),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            title,
            style: pw.TextStyle(
              fontSize: 13,
              fontWeight: pw.FontWeight.bold,
              color: colors.title,
            ),
          ),
          pw.Container(
            margin: const pw.EdgeInsets.only(top: 5, bottom: 10),
            height: 1.2,
            width: 72,
            color: colors.accent,
          ),
          ...children,
        ],
      ),
    );
  }

  static pw.Widget _itemsTable(
    List<BiodataItem> items,
    _PdfTemplateColors colors,
  ) {
    return pw.Table(
      columnWidths: const {
        0: pw.FlexColumnWidth(1.05),
        1: pw.FlexColumnWidth(1.85),
      },
      children: items.map((item) {
        return pw.TableRow(
          children: [
            pw.Padding(
              padding: const pw.EdgeInsets.only(bottom: 7, right: 10),
              child: pw.Text(
                item.label,
                style: pw.TextStyle(
                  fontSize: 9.5,
                  fontWeight: pw.FontWeight.bold,
                  color: colors.muted,
                ),
              ),
            ),
            pw.Padding(
              padding: const pw.EdgeInsets.only(bottom: 7),
              child: pw.Text(
                item.value,
                style: pw.TextStyle(
                  fontSize: 10,
                  height: 1.25,
                  color: colors.text,
                ),
              ),
            ),
          ],
        );
      }).toList(),
    );
  }

  static Future<pw.ImageProvider?> _loadProfileImage(String url) async {
    if (url.trim().isEmpty || !url.startsWith('http')) return null;
    try {
      return await networkImage(url);
    } catch (_) {
      return null;
    }
  }

  static String _initials(String name) {
    final parts = name.trim().split(RegExp(r'\s+'));
    if (parts.isEmpty || parts.first.isEmpty) return 'W';
    return parts.take(2).map((part) => part[0].toUpperCase()).join();
  }

  static _PdfTemplateColors _templateColors(BiodataTemplate template) {
    switch (template) {
      case BiodataTemplate.mainBioData:
      case BiodataTemplate.designSix:
        return const _PdfTemplateColors(
          title: PdfColor.fromInt(0xFF7A2444),
          text: PdfColor.fromInt(0xFF2E2026),
          muted: PdfColor.fromInt(0xFF7A6970),
          accent: PdfColor.fromInt(0xFFC24F7A),
          border: PdfColor.fromInt(0xFFF0CDD9),
          headerBackground: PdfColor.fromInt(0xFFFFF4F7),
        );
      case BiodataTemplate.designFour:
      case BiodataTemplate.designEight:
        return const _PdfTemplateColors(
          title: PdfColor.fromInt(0xFF17324D),
          text: PdfColor.fromInt(0xFF1F2933),
          muted: PdfColor.fromInt(0xFF64748B),
          accent: PdfColor.fromInt(0xFF2563A8),
          border: PdfColor.fromInt(0xFFD7DEE8),
          headerBackground: PdfColor.fromInt(0xFFF4F7FA),
        );
      case BiodataTemplate.designOne:
      case BiodataTemplate.designThree:
      case BiodataTemplate.designNine:
        return const _PdfTemplateColors(
          title: PdfColor.fromInt(0xFF1F3D35),
          text: PdfColor.fromInt(0xFF24312E),
          muted: PdfColor.fromInt(0xFF6D7774),
          accent: PdfColor.fromInt(0xFF0F8B6F),
          border: PdfColor.fromInt(0xFFD8E8E1),
          headerBackground: PdfColor.fromInt(0xFFF2FAF7),
        );
      case BiodataTemplate.designTwo:
      case BiodataTemplate.designTen:
        return const _PdfTemplateColors(
          title: PdfColor.fromInt(0xFF6F4316),
          text: PdfColor.fromInt(0xFF332817),
          muted: PdfColor.fromInt(0xFF806B45),
          accent: PdfColor.fromInt(0xFFD79A24),
          border: PdfColor.fromInt(0xFFF1D9A8),
          headerBackground: PdfColor.fromInt(0xFFFFF8E6),
        );
      case BiodataTemplate.designFive:
      case BiodataTemplate.designEleven:
        return const _PdfTemplateColors(
          title: PdfColor.fromInt(0xFF49316D),
          text: PdfColor.fromInt(0xFF2E263A),
          muted: PdfColor.fromInt(0xFF756A82),
          accent: PdfColor.fromInt(0xFF8B5CF6),
          border: PdfColor.fromInt(0xFFE5D6FF),
          headerBackground: PdfColor.fromInt(0xFFF8F3FF),
        );
      case BiodataTemplate.designSeven:
        return const _PdfTemplateColors(
          title: PdfColor.fromInt(0xFF813C12),
          text: PdfColor.fromInt(0xFF33251C),
          muted: PdfColor.fromInt(0xFF866554),
          accent: PdfColor.fromInt(0xFFF97316),
          border: PdfColor.fromInt(0xFFFFD8BA),
          headerBackground: PdfColor.fromInt(0xFFFFF4EA),
        );
    }
  }
}

class _PdfTemplateColors {
  const _PdfTemplateColors({
    required this.title,
    required this.text,
    required this.muted,
    required this.accent,
    required this.border,
    required this.headerBackground,
  });

  final PdfColor title;
  final PdfColor text;
  final PdfColor muted;
  final PdfColor accent;
  final PdfColor border;
  final PdfColor headerBackground;
}
